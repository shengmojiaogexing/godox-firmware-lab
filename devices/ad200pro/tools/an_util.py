#!/usr/bin/env python3
"""Shared helpers for the second-pass reverse-engineering scripts (an_*).

Parses analysis/disasm.txt (already generated by tools/analyze.py) into a
convenient {addr: function} map so the an_* scripts do not have to re-run the
expensive recursive CFG pass.

Author: fw-analyst (task-1).  Read-only helper: writes nothing.
"""
import json
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AN = os.path.join(ROOT, 'analysis')
BASE = 0x08003000

_HDR = re.compile(r'^; FUNC_([0-9a-f]{8})\s+file\+0x([0-9a-f]+)\s+(\d+) insns\s*calls=(.*)$')
_INSN = re.compile(r'^([0-9a-f]{8}): ([0-9a-f]+)\s+(.*)$')
_NOTE = re.compile(r'^([0-9a-f]{8}):\s+;\s*(.*)$')


def load_image():
    return open(os.path.join(ROOT, 'firmware', 'AD200pro_V1.60.bin'), 'rb').read()


DATA = load_image()
SIZE = len(DATA)
END = BASE + SIZE


def rd32(a):
    o = a - BASE
    return struct.unpack_from('<I', DATA, o)[0] if 0 <= o <= SIZE - 4 else None


def rd16(a):
    o = a - BASE
    return struct.unpack_from('<H', DATA, o)[0] if 0 <= o <= SIZE - 2 else None


def rd8(a):
    o = a - BASE
    return DATA[o] if 0 <= o < SIZE else None


def in_img(a):
    return BASE <= a < END


def ascii_at(a, maxlen=96):
    o = a - BASE
    if not (0 <= o < SIZE):
        return None
    out = bytearray()
    for i in range(o, min(SIZE, o + maxlen)):
        c = DATA[i]
        if 32 <= c < 127:
            out.append(c)
        else:
            break
    return out.decode() if len(out) >= 4 else None


def load_functions():
    """addr -> record from analysis/functions.json (ints already)."""
    funcs = json.load(open(os.path.join(AN, 'functions.json'), encoding='utf-8'))
    return {f['start']: f for f in funcs}


def parse_disasm():
    """addr -> list of (insn_addr, raw_hex, text, notes[]) sorted by insn_addr."""
    out = {}
    cur = None
    last = None
    for line in open(os.path.join(AN, 'disasm.txt'), encoding='utf-8'):
        if line.startswith('; FUNC_'):
            m = _HDR.match(line.rstrip('\n'))
            if m:
                cur = int(m.group(1), 16)
                out[cur] = []
                last = None
            continue
        m = _INSN.match(line.rstrip('\n'))
        if not m or cur is None:
            nm = _NOTE.match(line.rstrip('\n'))
            if nm and cur is not None and out.get(cur):
                out[cur][-1][3].append(nm.group(2).strip())
            continue
        a = int(m.group(1), 16)
        if m.group(3).lstrip().startswith(';'):
            if last is not None and out[cur]:
                out[cur][-1][3].append(m.group(3).strip())
            continue
        out[cur].append([a, m.group(2), m.group(3).rstrip(), []])
        last = a
    for a in out:
        out[a].sort(key=lambda x: x[0])
    return out


def lit_words():
    """lit_addr -> value (from literals.json)."""
    lits = json.load(open(os.path.join(AN, 'literals.json'), encoding='utf-8'))
    return {l['addr']: l for l in lits}


def show(addr, insns=None, notes=True):
    """Pretty-print one function body (sorted by address)."""
    if insns is None:
        insns = DIS.get(addr, [])
    rec = FUNCS.get(addr, {})
    print('\n==== FUNC_%08x  file+0x%05x  %d insns  end=0x%08x' % (
        addr, addr - BASE, len(insns), rec.get('end', 0)))
    if rec.get('callers'):
        print('   callers: %s' % ' '.join('0x%08x' % c for c in rec['callers']))
    if rec.get('calls'):
        print('   calls  : %s' % ' '.join('0x%08x' % c for c in rec['calls']))
    if rec.get('strings'):
        print('   strings: %r' % rec['strings'][:16])
    seen = []
    for m in rec.get('mmio', []):
        t = '%s:%s' % (m['rw'], m['name'])
        if t not in seen:
            seen.append(t)
    if seen:
        print('   mmio   : %s' % ' '.join(seen))
    for a, raw, text, ns in insns:
        print('%08x  %-8s %-30s' % (a, raw, text))
        if notes:
            for n in ns:
                print('             %s' % n)


def callees(addr):
    return FUNCS.get(addr, {}).get('calls', [])


def callers(addr):
    return FUNCS.get(addr, {}).get('callers', [])


def walk_tree(addr, depth=0, maxdepth=3, seen=None):
    seen = set() if seen is None else seen
    pad = '  ' * depth
    rec = FUNCS.get(addr, {})
    print('%s0x%08x  (%d ins) %s' % (pad, addr, rec.get('insn_count', 0),
                                     (rec.get('strings') or [''])[0][:60]))
    if depth >= maxdepth or addr in seen:
        return
    seen.add(addr)
    for c in rec.get('calls', []):
        walk_tree(c, depth + 1, maxdepth, seen)


def render_lit(a):
    v = rd32(a)
    if v is None:
        return ''
    s = ascii_at(v) if in_img(v) else None
    return '0x%08x (%s)%s' % (v, cls(v), (' "%s"' % s) if s else '')


def cls(v):
    if v is None:
        return 'none'
    if v == 0:
        return 'zero'
    if BASE <= v < END:
        return 'flash'
    if 0x08000000 <= v < 0x08010000:
        return 'flash-hi'
    if 0x20000000 <= v < 0x20010000:
        return 'ram'
    if 0x40000000 <= v < 0x40100000:
        return 'periph'
    if 0x48000000 <= v < 0x48002000:
        return 'gpio'
    if 0xE0000000 <= v < 0xE0100000:
        return 'scs'
    if v < 0x10000:
        return 'small'
    return 'other'


FUNCS = load_functions()
DIS = parse_disasm()
LITS = lit_words()

if __name__ == '__main__':
    import sys
    for a in sys.argv[1:]:
        show(int(a, 0))
