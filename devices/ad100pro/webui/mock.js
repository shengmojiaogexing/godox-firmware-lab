  function mmioWord(addr) {
    for (var i = 0; i < MMIO_WORDS.length; i++) {
      var a = MMIO_WORDS[i][0];
      if (addr >= a && addr < a + 4) return MMIO_WORDS[i][1];
    }
    return null;
  }
  function memByte(addr) {
    addr = addr >>> 0;
    // Flash：夹具覆盖处为真实字节，其余为确定性伪字节（与合成指令的字节一致）
    if (addr >= IMAGE_BASE && addr < IMAGE_END) {
      var f = fixtureAt(addr);
      if (f) return parseInt(f.bytes.substr((addr - f.addr) * 2, 2), 16);
      var sy = synthInsn(addr & ~1);
      return parseInt(sy.bytes.substr((addr & 1) * 2, 2), 16);
    }
    // RAM：UART 缓冲区可读文本 + 栈附近值 + 其余确定性填充
    if (addr >= RAM_BASE && addr < RAM_BASE + RAM_SIZE) {
      if (state && addr >= UART_BUF && addr < UART_BUF + state.uart.length) {
        return state.uart.charCodeAt(addr - UART_BUF) & 0xFF;
      }
      if (state && addr >= (state.sp - 8) && addr < (state.sp + 96)) {
        var off = (addr - (state.sp - 8));
        return hashByte(addr, 0x51ED2701) & 0x3F ? 0 : hashByte(addr, 0x1234ABCD);
      }
      return (hash32(addr ^ 0x2000BEEF) % 11 === 0) ? (hash32(addr ^ 0x77) & 0xFF) : 0x00;
    }
    // MMIO
    var w = mmioWord(addr);
    if (w != null) return (w >>> (((addr - (addr & ~3)) & 3) * 8)) & 0xFF;
    if ((addr >= 0x40000000 && addr < 0x40100000) ||
        (addr >= 0x48000000 && addr < 0x48002000) ||
        (addr >= 0xE0000000 && addr < 0xE0010000)) {
      return (hash32(addr ^ 0xE000) % 13 === 0) ? (hash32(addr) & 0xFF) : 0x00;
    }
    return 0x00;
  }
  function memHex(addr, len) {
    addr = toInt(addr);
    if (addr == null) addr = UART_BUF;
    len = toInt(len);
    if (!len || len < 1) len = 256;
    if (len > 4096) len = 4096;
    var s = '';
    for (var i = 0; i < len; i++) s += hex2(memByte((addr + i) >>> 0));
    return { addr: addr >>> 0, len: len, hex: s };
  }

