  function cmd(body) {
    body = body || {};
    var name = body.cmd || body.command || body.action;
    var addr;
    switch (name) {
      case 'run':
        state.running = true;
        lastTick = now();
        return { ok: true, cmd: name, running: true };
      case 'pause':
        state.running = false;
        return { ok: true, cmd: name, running: false };
      case 'step':
        state.running = false;
        stepOnce();
        return { ok: true, cmd: name, pc: state.pc };
      case 'step_over':
        state.running = false;
        var insn = insnAt(state.pc);
        if (/^(bl|blx)$/.test(insn.mnem)) {
          var next = (state.pc + insn.len) >>> 0;
          state.pc = next;
          state.insnCount++;
        } else {
          stepOnce();
        }
        return { ok: true, cmd: name, pc: state.pc };
      case 'reset':
        doReset();
        return { ok: true, cmd: name, pc: state.pc };
      case 'set_pc':
      case 'setpc':
        addr = toInt(body.addr != null ? body.addr : (body.address != null ? body.address : body.pc));
        if (addr == null) return { ok: false, error: '地址非法' };
        addr = addr & ~1;
        if (!memAddrOk(addr)) return { ok: false, error: '地址不在可映射区间' };
        state.pc = addr;
        state.running = false;
        state.regs[15] = addr;
        return { ok: true, cmd: 'set_pc', pc: addr };
      case 'bp_add':
        return addBp(body.addr != null ? body.addr : (body.address != null ? body.address : body.pc));
      case 'bp_del':
        return delBp(body.addr != null ? body.addr : (body.address != null ? body.address : body.pc));
      case 'battery': {
        var mv = toInt(firstDef(body.mv, body.battery_mv, body.value, body.voltage_mv));
        if (mv == null) return { ok: false, error: 'battery mv 非法' };
        mv = Math.max(2600, Math.min(4200, mv));
        state.inputs.battery_mv = mv;
        state.inputs.battery_pct = Math.round((mv - 2600) * 100 / 1600);
        state.inputs.adc = {
          ch0: Math.round((mv - 2600) / 1600 * 4095),
          ch1: state.inputs.adc && state.inputs.adc.ch1 != null ? state.inputs.adc.ch1 : 0x01F2
        };
        inputEvent('battery', null, { mv: mv });
        appendUart('[INPUT] battery=' + mv + 'mV\n');
        return { ok: true, cmd: name, battery_mv: mv, battery_pct: state.inputs.battery_pct };
      }
      case 'key':
      case 'key_down': {
        var key = firstDef(body.key, body.name, body.button);
        if (key == null) return { ok: false, error: 'key 非法' };
        key = String(key);
        var down = body.down == null ? true : !!body.down;
        if (!state.inputs.keys) state.inputs.keys = {};
        state.inputs.keys[key] = down;
        updatePressed();
        inputEvent(down ? 'key_down' : 'key_up', key);
        return { ok: true, cmd: name, key: key, down: down };
      }
      case 'key_up': {
        var keyUp = firstDef(body.key, body.name, body.button);
        if (keyUp == null) return { ok: false, error: 'key 非法' };
        keyUp = String(keyUp);
        if (!state.inputs.keys) state.inputs.keys = {};
        state.inputs.keys[keyUp] = false;
        updatePressed();
        inputEvent('key_up', keyUp);
        return { ok: true, cmd: name, key: keyUp, down: false };
      }
      case 'key_press': {
        var keyP = firstDef(body.key, body.name, body.button);
        if (keyP == null) return { ok: false, error: 'key 非法' };
        keyP = String(keyP);
        var ms = toInt(firstDef(body.ms, body.duration, 80));
        if (ms == null || ms <= 0) ms = 80;
        if (!state.inputs.keys) state.inputs.keys = {};
        state.inputs.keys[keyP] = true;
        updatePressed();
        inputEvent('key_press', keyP, { ms: ms });
        setTimeout((function (k, d) {
          return function () {
            if (state.inputs.keys && state.inputs.keys[k] !== undefined) {
              state.inputs.keys[k] = false;
              updatePressed();
            }
          };
        })(keyP, ms), ms);
        return { ok: true, cmd: name, key: keyP, ms: ms };
      }
      case 'screen_save': {
        saveCount++;
        var savePath = 'out/screen_save_' + ('000' + saveCount).slice(-3) + '.png';
        state.inputs.screen_save = savePath;
        state.lastScreenSave = savePath;
        inputEvent('screen_save', null, { path: savePath });
        return { ok: true, cmd: name, path: savePath, mock: true };
      }
      case 'clear_inputs':
      case 'key_clear': {
        var keysObj = state.inputs.keys || {};
        Object.keys(keysObj).forEach(function (k) { keysObj[k] = false; });
        state.inputs.pressed = [];
        state.inputs.last = { type: 'clear' };
        inputEvent('clear_inputs', null);
        return { ok: true, cmd: name, inputs: clonePlain(state.inputs) };
      }
      case 'jump_main':
      case 'skip_boot':
      case 'fastboot':
      case 'boot_interactive':
      case 'boot':
      case 'start': {
        state.insnCount += 1200000;
        state.virtualTicks = (state.virtualTicks || 0) + 45;
        state.pc = 0x0800D008;
        state.regs[15] = state.pc;
        state.running = false;
        state.pcName = '0x0800D008';
        state.taskPhase = 'scheduler';
        state.inMainLoop = true;
        if (state.rf) state.rf.state = 'RX';
        pushLog({ dir: '!', addr: 0x0800D008, reg: 'BOOT', value: 1, pc: state.pc, time: state.insnCount, note: '进入主循环' });
        appendUart('[BOOT] skip to main loop 0x0800D008\n');
        return {
          ok: true, cmd: name, pc: state.pc, insn: state.insnCount,
          pcName: state.pcName, taskPhase: state.taskPhase,
          inputs: clonePlain(state.inputs), rf: clonePlain(state.rf),
          rfInitialized: !!(state.rf && state.rf.state === 'RX'),
          irqCounts: clonePlain(state.irq_counts),
          lcd: buildScreen()
        };
      }
      case 'rf_init': {
        state.rf.state = 'RX';
        state.rf.gdo0 = 0;
        pushLog({ dir: '!', addr: 0, reg: 'RF_INIT', value: 1, pc: state.pc, time: state.insnCount, note: 'CC2500 初始化 → RX' });
        return { ok: true, cmd: name, rf: clonePlain(state.rf), rfInitialized: true };
      }
      case 'rf_rx':
      case 'rf_inject_rx':
      case 'inject_rf': {
        var hexIn = String(firstDef(body.hex, body.data, body.payload, '') || '');
        var hx = hexIn.replace(/0x/gi, '').replace(/[\s,:-]/g, '').toUpperCase();
        if (!hx || hx.length % 2 !== 0 || !/^[0-9A-F]+$/.test(hx)) {
          return { ok: false, error: 'rf_rx hex 非法（需偶数字节）' };
        }
        state.rf.rx_count++;
        state.rf.gdo0 = 1;
        state.rf.last_rx = hx.toLowerCase();
        state.rf.rx_fifo = '';
        state.irq_counts[23] = (state.irq_counts[23] || 0) + 1;
        state.irqLog.push({ insn: state.insnCount, irq: 23, handler: 0x0800BA00, source: 'GDO0' });
        if (state.irqLog.length > 40) state.irqLog.shift();
        inputEvent('rf_rx', null, { path: hx });
        setTimeout(function () { if (state.rf) state.rf.gdo0 = 0; }, 120);
        return {
          ok: true, cmd: name, len: hx.length / 2,
          rf: clonePlain(state.rf),
          irqCounts: clonePlain(state.irq_counts)
        };
      }
      case 'rf_status':
      case 'rf':
        return { ok: true, cmd: name, rf: clonePlain(state.rf) };
      case 'irq_status':
        return {
          ok: true, cmd: name, irqCounts: clonePlain(state.irq_counts),
          irqLog: clonePlain(state.irqLog), inIsr: state.inIsr,
          realIrq: state.realIrq, tim14Count: state.tim14Count
        };
      default:
        return { ok: false, status: 404, error: 'mock 不支持的命令: ' + name };
    }
  }

